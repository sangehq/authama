// Command gonotices writes third-party-notices-go.md: the licence of every Go
// module compiled into the authama binary, and of the Go toolchain's standard
// library, which every binary links too.
//
// The release archives already ship third-party-notices.md for the web UI's
// Tabler, Bootstrap and Popper files. The Go libraries are linked statically, and
// their MIT, BSD and Apache licences ask for the notice to travel with a binary
// that carries them, so this file ships beside it.
//
// It lists the union over every release GOOS, because a module can be linked on
// one platform only (golang.org/x/sys/windows, go-isatty). `make notices` runs it;
// `make notices-check`, part of `make ci`, fails when the file is stale.
//
// Usage (from src/): go run ./internal/tools/gonotices -o ../third-party-notices-go.md
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/sangehq/authama/src/internal/util/fs"
)

// releaseOSes are the GOOS values the release builds (src/.goreleaser.yaml).
var releaseOSes = []string{"linux", "darwin", "windows"}

// licenceNames are tried in order in a module's root directory.
var licenceNames = []string{"LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "COPYING", "license", "License"}

type module struct {
	Path    string
	Version string
	Dir     string
	Main    bool
}

type pkg struct {
	Module *module
}

func main() {
	out := flag.String("o", "", "file to write (default: stdout)")
	check := flag.Bool("check", false, "compare with the -o file instead of writing it; exit 1 when it is stale")
	mainPkg := flag.String("main", "./cmd/authama", "package whose dependencies are listed")
	flag.Parse()

	text, err := render(*mainPkg)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gonotices:", err)
		os.Exit(1)
	}
	if *check {
		if *out == "" {
			fmt.Fprintln(os.Stderr, "gonotices: -check needs -o")
			os.Exit(2)
		}
		have, err := os.ReadFile(*out)
		// A Windows checkout may hold the file with CRLF endings; the text is
		// what matters, not how git wrote it to disk.
		if err != nil || strings.ReplaceAll(string(have), "\r\n", "\n") != text {
			fmt.Fprintf(os.Stderr, "gonotices: %s is stale; run make notices and commit it\n", *out)
			os.Exit(1)
		}
		return
	}
	if *out == "" {
		_, _ = os.Stdout.WriteString(text)
		return
	}
	if err := fs.WriteTextAtomic(*out, text, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gonotices:", err)
		os.Exit(1)
	}
}

func render(mainPkg string) (string, error) {
	mods := map[string]module{}
	for _, goos := range releaseOSes {
		found, err := linkedModules(mainPkg, goos)
		if err != nil {
			return "", fmt.Errorf("GOOS=%s: %w", goos, err)
		}
		for _, m := range found {
			mods[m.Path] = m
		}
	}
	if len(mods) == 0 {
		// A listing that found nothing is a broken listing, not a binary with
		// no dependencies.
		return "", errors.New("no modules found; is this run from the module root?")
	}
	paths := make([]string, 0, len(mods))
	for p := range mods {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b strings.Builder
	b.WriteString("# Third-party notices: Go modules\n\n")
	b.WriteString("Every authama binary statically links the Go standard library and the\n")
	fmt.Fprintf(&b, "%d Go modules below. Each licence follows in full.\n", len(paths))
	b.WriteString("This file is generated by `make notices`; do not edit it by hand.\n")
	b.WriteString("The web UI's embedded files are in third-party-notices.md.\n\n")

	goroot, err := goEnv("GOROOT")
	if err != nil {
		return "", err
	}
	// Homebrew moves the toolchain's LICENSE one level above GOROOT.
	stdlib, err := licence(goroot)
	if err != nil {
		stdlib, err = licence(filepath.Dir(goroot))
	}
	if err != nil {
		return "", fmt.Errorf("the Go standard library: %w", err)
	}
	section(&b, "Go standard library", "", stdlib)

	for _, p := range paths {
		m := mods[p]
		text, err := licence(m.Dir)
		if err != nil {
			return "", fmt.Errorf("%s %s: %w", m.Path, m.Version, err)
		}
		section(&b, m.Path, m.Version, text)
	}
	// One trailing newline, not the blank line the last section leaves.
	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

func section(b *strings.Builder, name, version, text string) {
	if version != "" {
		fmt.Fprintf(b, "## %s %s\n\n", name, version)
	} else {
		fmt.Fprintf(b, "## %s\n\n", name)
	}
	b.WriteString("```text\n")
	b.WriteString(strings.TrimRight(strings.ReplaceAll(text, "\r\n", "\n"), "\n"))
	b.WriteString("\n```\n\n")
}

func linkedModules(mainPkg, goos string) ([]module, error) {
	cmd := exec.Command("go", "list", "-deps", "-json=Module", mainPkg)
	cmd.Env = append(os.Environ(), "GOOS="+goos, "CGO_ENABLED=0")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w: %s", err, strings.TrimSpace(stderr.String()))
	}
	var mods []module
	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var p pkg
		if err := dec.Decode(&p); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, err
		}
		if p.Module == nil || p.Module.Main {
			continue
		}
		mods = append(mods, *p.Module)
	}
	return mods, nil
}

func licence(dir string) (string, error) {
	if dir == "" {
		return "", errors.New("module not downloaded (run go mod download)")
	}
	for _, name := range licenceNames {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err == nil {
			return string(data), nil
		}
	}
	return "", fmt.Errorf("no licence file in %s", dir)
}

func goEnv(key string) (string, error) {
	out, err := exec.Command("go", "env", key).Output()
	if err != nil {
		return "", fmt.Errorf("go env %s: %w", key, err)
	}
	return strings.TrimSpace(string(out)), nil
}
